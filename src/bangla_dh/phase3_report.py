    confirm = settings["confirmation"]
    w(f"Confirmation: from each style's best layout, {confirm['seeds']} more iterated local searches of "
      f"{confirm['ils_iterations']:,} iterations with perturbation strengths "
      f"{', '.join(f'{a}–{b}' for a, b in confirm['strengths'])}: " +
      "; ".join(f"{style} {'improved' if any(r['improved'] for r in search[style]['confirmation']) else 'no improvement'}"
                for style in STYLES) + ".")
    w("")
    w("Many independent seeds reaching the same score is evidence that the search is not stuck, not a proof; "
      "the elementary lower bound below shows how much room a proof would still have to close.")
    w("")

    # --- 5 layouts
    w("## 5. Best layouts")
    w("")
    for style in STYLES:
        s = scores[style][TRAIN]["unrounded"]
