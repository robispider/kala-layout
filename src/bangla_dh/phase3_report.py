    w("Escapes common to all styles are the units v1 puts on no key (ZWNJ, ZWJ, —, ॥, ঽ). The rest are rule "
      "collisions: C cannot type the same independent vowel twice (এএফসি), A and D cannot type hasant + vowel "
      "sign (a legacy-conversion artifact), and B and D cannot type an independent vowel followed by its own "
      "sign or a doubled sign (ইি, িি: typing errors in the corpus). তিনিই, এটিই and সিইও are typed with three "
      "presses in B and D.")
    w("")
    w("NFC round trip `NFC(decode(encode(T))) = NFC(T)`, the decoder starting from the label stream alone:")
    w("")
    w("| Style | Text set | Texts | Round trip OK | Failures | With escapes |")
    w("| --- | --- | --- | --- | --- | --- |")
    for style in STYLES:
        for source, r in ev["round_trip"][style].items():
            w(f"| {style} | {source} | {r['texts']:,} | {r['round_trip_ok']:,} | {r['failures']} | "
              f"{r['texts_with_escapes']:,} |")
    w("")

    # --- 3 J1
    w("## 3. J1 and UniJoy (task 3)")
    w("")
    w("`KeyModel.modifier_effort` gives M; both Phase 2 scoring routes (unit tables and encoded tokens) and the "
      "independent verifier report J1 next to J0. UniJoy (Kala's file, base + Shift only) rescored:")
    w("")
    w("| Corpus | Grid | J0 | M | J1 | E1 | E2 | same finger | keystrokes per non-space unit |")
    w("| --- | --- | --- | --- | --- | --- | --- | --- | --- |")
    for corpus in CORPORA:
        for grid, s in uj[corpus].items():
            w(f"| {corpus} | {GRID_LABEL[grid]} | {_f(s['J0'])} | {_f(s['M'])} | {_f(s['J1'])} | {_f(s['E1'])} | "
              f"{_f(s['E2'])} | {_f(s['E2_same_finger'])} | {_f(s['keystrokes_per_non_space_unit'])} |")
    w("")
    w(f"UniJoy's J0 equals the Phase 2 values exactly: {'yes' if ev['unijoy']['J0_matches_phase2'] else 'NO'}.")
    w("")

    # --- 4 search
    settings = search[STYLES[0]]["settings"]
    w("## 4. Search (task 4)")
    w("")
    w("Code: `bangla_dh.search.anneal`. Per style: a quadratic assignment of 52 labels to 52 slots with the "
      "fixed keys folded into a linear term, scored with O(1) swap deltas. Each run: simulated annealing over "
      "pair swaps (base↔Shift included), geometric cooling from T0 (mean uphill delta of 2,000 random swaps "
      f"/ ln 2) to T0 × {settings['t_ratio']:g}, {settings['sa_steps']:,} steps; steepest descent to a "
      f"swap-local optimum; {settings['ils_iterations']:,} iterations of iterated local search (perturbation "
      f"by {settings['ils_strength'][0]}–{settings['ils_strength'][1]} random pair swaps or whole-key "
      f"exchanges). {settings['seeds']} seeds per style; {settings['starts']}. Frequencies: {settings['frequencies']}.")
    w("")
    w("| Style | Runs | Best J1 (train) | Median | Worst | Runs reaching the best | Distinct best layouts | CPU time |")
    w("| --- | --- | --- | --- | --- | --- | --- | --- |")
    for style in STYLES:
        st = search[style]["statistics"]
        w(f"| {style} | {st['runs']} | {st['best']:.6f} | {st['median']:.6f} | {st['worst']:.6f} | "
          f"{st['runs_reaching_best']} | {st['distinct_best_layouts']} | {st['seconds_total'] / 60:.1f} min |")
