ROWS = (tuple("QWERTYUIOP"), tuple("ASDFGHJKL"), tuple("ZXCVBNM"))
GRID_LABEL = {"unrounded": "unrounded", "one_decimal": "one decimal", "traditional_unrounded": "traditional unrounded"}


def _label(label: str) -> str:
    return _show(label).replace("|", "\\|")


def layout_tables(layout: dict[str, str]) -> list[str]:
    by_slot = {slot: label for label, slot in layout.items()}
    out = []
    for row in ROWS:
        out.append("| | " + " | ".join(row) + " |")
        out.append("| --- |" + " --- |" * len(row))
        for layer in ("shift", "base"):
            out.append(f"| {'Shift' if layer == 'shift' else 'base'} | " +
                       " | ".join(_label(by_slot.get(f"{key}/{layer}", "")) for key in row) + " |")
        out.append("")
    return out


def build_report(ev: dict) -> str:
    problem = load_problem()
    scores, uj = ev["scores"], ev["unijoy"]["scores"]
    search = ev["search"]
    ok = acceptance(ev)
    best_style = min(STYLES, key=lambda s: scores[s][HELDOUT]["unrounded"]["J1"])
    uj_j1 = uj[HELDOUT]["unrounded"]["J1"]
    L: list[str] = []
    w = L.append

    w("# Phase 3 report: vowel-entry styles, J1 and seeded search")
    w("")
    w("Generated by `bangla-dh evaluate-phase3`. Machine-readable record: [phase3.json](phase3.json); search "
      "records with every run: [search/](search/); hashes of every input and output: "
      "[run-manifest.json](run-manifest.json).")
    w("")
    w("Owner decisions D1, D2 and D4 of 10 October 2026 define the problem (RESEARCH_SPEC sections 4, 6.6, 7.1). "
      "D3 (fingering) and D6 (middle–index benefit) use their defaults: the model-optimal ANSI grid and the "
      "benefit kept. D5 (integer scale) does not arise before Phase 4. Kala's data was read in place and never "
      "modified.")
    w("")
    w("All layouts below are **best found** (RESEARCH_SPEC section 14): the lowest J1 among the layouts the "
      "stated search visited. Nothing here is a proof of optimality.")
    w("")
    w("## Summary")
    w("")
    w("| Style | Vowel entry | Keystrokes per non-space unit | J1 held-out | J0 held-out | J1 vs UniJoy |")
    w("| --- | --- | --- | --- | --- | --- |")
    for style in STYLES:
        s = scores[style][HELDOUT]["unrounded"]
        w(f"| {style} | {STYLE_NAMES[style]} | {_f(s['keystrokes_per_non_space_unit'])} | {_f(s['J1'])} | "
          f"{_f(s['J0'])} | {100 * (s['J1'] / uj_j1 - 1):+.1f} % |")
    u = uj[HELDOUT]["unrounded"]
    w(f"| UniJoy | Kala's file (independent vowel = ্ + sign) | {_f(u['keystrokes_per_non_space_unit'])} | "
      f"{_f(u['J1'])} | {_f(u['J0'])} | |")
    w("")
    w(f"* Lowest held-out J1: **style {best_style}** ({_f(scores[best_style][HELDOUT]['unrounded']['J1'])}, "
      f"UniJoy {_f(uj_j1)}). J is effort per unit of text (space included), so styles with more keystrokes "
      "pay for them in E1, M and E2.")
    w("* Checks: " + ", ".join(f"{name}: {'PASS' if v else 'FAIL'}" for name, v in ok.items()) + ".")
    w("")

    # --- 1 problem
    w("## 1. Problem (task 1)")
    w("")
    w(f"File: [`data/problem-v1.json`](../../data/problem-v1.json), problem SHA-256 "
      f"`{problem['problem_sha256'][:16]}…`, built from the frozen inventory and the style definitions "
      "(`bangla-dh build-problem`).")
    w("")
    w(f"* **Slots:** the 26 letter keys ({' '.join(SEARCHED_KEYS)}) × base/Shift = {len(problem['slots'])}.")
    fixed = ", ".join(f"{_label(k)} {v}" for k, v in problem["fixed"].items())
    w(f"* **Fixed:** {fixed}; `.` on `./base` (outside the symbol inventory, not a typing unit).")
    w(f"* **Searched (every style):** 35 consonants, {' '.join(_label(s) for s in ['্', 'ং', 'ঃ', 'ঁ', 'ৎ', '।'])}, "
      "plus the style's 11 vowel keys: 52 labels on 52 slots.")
    w(f"* **Not on v1 keys:** {' '.join(problem['not_on_keys']['third_layer'])} (third layer later); ZWNJ, ZWJ "
      "(no key). Text containing them is typed outside the model (escaped).")
    w("* **Objective:** J1 = J0 + Σ u_i M(L(c_i)); a shifted key costs the other hand's Shift key from the same "
      "grid (K(LShift) = 3.308 for right-hand keys, K(RShift) = 4.610 for left-hand keys), λ_m = 1, Q = 0. "
      "Space is the thumb (no cost); a repeated key costs its effort twice and no bigram penalty.")
    w("")

    # --- 2 styles
    w("## 2. Vowel-entry styles (task 2)")
    w("")
    w("Code: `bangla_dh.bangla.styles`. Each style is a typing machine that sees only key labels; the encoder "
      "picks, unit by unit, the fewest keystrokes whose simulated output is exactly the text. Units no rule can "
      "type are escaped (typed outside the model; they break bigrams). Examples (key labels):")
    w("")
    words = list(next(iter(ev["examples"].values())))
    w("| Word | " + " | ".join(STYLES) + " |")
    w("| --- |" + " --- |" * len(STYLES))
    for word in words:
        cells = [" ".join(_label(x) for x in ev["examples"][s][word]) for s in STYLES]
        w(f"| {word} | " + " | ".join(cells) + " |")
    w("")
    w("Style D: after a consonant one tap gives the vowel sign, elsewhere the independent vowel; the same key "
      "again right after it produced a sign turns the sign into the independent vowel (ব ি ি → বই). The open "
      "point of section 7.1 is settled as: a vowel key right after ্ gives the independent vowel, so hasant + "
      "vowel sign (invalid text) is escaped, as in A.")
    w("")
    w("Repeated presses in B and D (owner rule of 10 October 2026, timing-free): consecutive presses of one vowel "
      "key whose first press gave a sign (always in B, after a consonant in D) are split into pairs, with one "
      "single press first when their number is odd. A single is the sign, a pair the independent vowel: 3 presses "
      "give ি ই (তিনিই), 4 give ই ই, 5 give ি ই ই. The next different key ends the run; no timer is needed. "
      "Before this rule B and D escaped তিনিই; with it, D needs 4 presses for নইই (3 before). C is unchanged.")
    w("")
    w("Keystrokes and escapes (escaped units are part of N but cost nothing):")
    w("")
    w("| Style | Corpus | Keystrokes per non-space unit | Escaped units | Share of N | Most escaped |")
    w("| --- | --- | --- | --- | --- | --- |")
    for style in STYLES:
        for corpus in CORPORA:
            t = ev["keystroke_tables"][f"{style} {corpus}"]
            top = ", ".join(f"{_label(k)} {c:,}" for k, c in t["escaped_top"][:6])
            w(f"| {style} | {corpus} | {_f(t['keystrokes_per_non_space_unit'])} | {t['escaped_units']:,} | "
              f"{_pct(t['escaped_share'], 3)} | {top} |")
