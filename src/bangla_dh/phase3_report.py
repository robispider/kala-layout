    for style in STYLES:
        for corpus in CORPORA:
            for grid in ("unrounded", "one_decimal"):
                s = scores[style][corpus][grid]
                w(f"| {style} | {corpus} | {GRID_LABEL[grid]} | {_f(s['J1'])} | {_f(s['J0'])} | {_f(s['E1'])} | "
                  f"{_f(s['E2'])} | {_f(s['M'])} | {_pct(s['same_finger_bigram_frequency'])} | "
                  f"{_f(s['E2_same_finger'])} | {_f(s['E2_neighbour_penalty'])} | {_f(s['E2_neighbour_benefit'])} |")
    for corpus in CORPORA:
        for grid in ("unrounded", "one_decimal"):
            s = uj[corpus][grid]
            w(f"| UniJoy | {corpus} | {GRID_LABEL[grid]} | {_f(s['J1'])} | {_f(s['J0'])} | {_f(s['E1'])} | "
              f"{_f(s['E2'])} | {_f(s['M'])} | | {_f(s['E2_same_finger'])} | {_f(s['E2_neighbour_penalty'])} | "
              f"{_f(s['E2_neighbour_benefit'])} |")
    w("")
    gaps = {style: scores[style][HELDOUT]["unrounded"]["J1"] - scores[style][TRAIN]["unrounded"]["J1"]
            for style in STYLES}
    w("Train → held-out change of J1: " + ", ".join(f"{s} {gaps[s]:+.4f}" for s in STYLES) +
      f"; UniJoy {uj[HELDOUT]['unrounded']['J1'] - uj[TRAIN]['unrounded']['J1']:+.4f}.")
    w("")

    # --- 7 checks
    w("## 7. Checks")
    w("")
    w("| Style | Search J1 | Table scorer J1 (train) | Verifier J1 (held-out) | Table J1 (held-out) | Relative difference | Pass |")
    w("| --- | --- | --- | --- | --- | --- | --- |")
    for style in STYLES:
        c = ev["checks"][style]
        w(f"| {style} | {c['search_record_J1']:.12f} | {c['table_J1']:.12f} | {c['verifier']['J1']:.12f} | "
          f"{scores[style][HELDOUT]['unrounded']['J1']:.12f} | {c['verifier_vs_tables_max_relative_difference']:.1e} | "
          f"{'PASS' if c['instance_pass'] and c['verifier_pass'] else 'FAIL'} |")
    w("")
    w("The verifier (`scoring.verify.verify_style`) reads the held-out corpus text itself and implements every "
      "style as direct rules, sharing no code with the typing machines, the tables or the search; it must also "
      "match N, the keystroke count and the escape count exactly.")
    w("")
    for name, value in ok.items():
        w(f"* {'PASS' if value else 'FAIL'}: {name}")
    w("")

    # --- 8 bounds
    w("## 8. Elementary lower bound (context for Phase 4)")
    w("")
    w("LB0 per style (RESEARCH_SPEC 8.3, 52-slot J1 scope, training frequencies): fixed-key constant + "
      "rearrangement minimum of Σ u·C + each label's cheapest fixed-key penalty + every searched pair at "
      "min B = −0.2. Valid but weak.")
    w("")
    w("| Style | LB0 | Best found | Gap |")
    w("| --- | --- | --- | --- |")
    for style in STYLES:
        lb = ev["lower_bound_0"][style]["LB0"]
        ub = scores[style][TRAIN]["unrounded"]["J1"]
        w(f"| {style} | {_f(lb)} | {_f(ub)} | {100 * (ub - lb) / max(1, abs(ub)):.1f} % |")
    w("")

    # --- 9 findings
    w("## 9. Findings and points for the owner")
    w("")
    order = sorted(STYLES, key=lambda st: scores[st][HELDOUT]["unrounded"]["J1"])
    d, a_ = scores["D"][HELDOUT]["unrounded"], scores["A"][HELDOUT]["unrounded"]
    c = scores["C"][HELDOUT]["unrounded"]
    w(f"* **Style ranking (held-out J1):** {' < '.join(order)}. D's lead over A ({_f(a_['J1'] - d['J1'])}) comes "
      f"from E1 ({_f(a_['E1'] - d['E1'])}): A types every independent vowel as two keys "
      f"({_f(a_['keystrokes_per_non_space_unit'])} against {_f(d['keystrokes_per_non_space_unit'])} keystrokes per "
      f"non-space unit). C is far behind ({_f(c['J1'] - d['J1'])} more than D) because every vowel sign (about 27 % of "
      "non-space units) costs two keystrokes.")
