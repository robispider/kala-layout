"""Write analyzer configuration files (effort_*_config.dat format) from the
reconstructed effort model, so the published comparison can be recomputed
on unrounded model grids instead of the published one-decimal grids.
"""
from __future__ import annotations

from .effort_model import EffortParams, Finger, effort_grid, fingers_for, traditional_fingers
from .keyboards import Keyboard

# Analyzer layout_full positions (4 rows) to physical keys.
_NUMBER = ["1", "2", "3", "4", "5", "6", "7", "8", "9", "0", "-", "="]
_TOP = ["Q", "W", "E", "R", "T", "Y", "U", "I", "O", "P", "[", "]"]
_HOME = ["A", "S", "D", "F", "G", "H", "J", "K", "L", ";", "'"]
_BOTTOM = {
    # 'angle' (Colemak-DH angle mod on ISO): the left bottom row moves one key
    # left, so analyzer column 0 is the ISO backslash key and B is unused.
    "angle": ["\\", "Z", "X", "C", "V", "N", "M", ",", ".", "/"],
    "std": ["Z", "X", "C", "V", "B", "N", "M", ",", ".", "/"],
}

_PENALTIES = """penalties:
 2.5  3.0  4.0  #same-finger
 0.5  1.0  1.5  #pinky-ring
 0.1  0.2  0.3  #ring-middle
-0.2 -0.1  0.0  #middle-index
"""


def position_rows(bottom: str) -> list[list[str]]:
    return [_NUMBER, _TOP, _HOME, _BOTTOM[bottom]]


def model_config_text(keyboard: Keyboard, params: EffortParams, *, fingers: str, bottom: str,
                      decimals: int | None = None) -> str:
    """Config text for ``fingers`` = "optimal" | "traditional" and ``bottom`` =
    "angle" | "std". ``decimals`` rounds efforts like the published grids."""
    assignment = traditional_fingers(keyboard) if fingers == "traditional" else None
    grid = effort_grid(keyboard, params, assignment)
    by_id: dict[str, Finger] = {f.finger_id: f for f in fingers_for(keyboard, params)}
    rows = position_rows(bottom)

    def effort_text(value: float) -> str:
        return repr(value) if decimals is None else f"{value:.{decimals}f}"

    lines = [f"# generated by bangla_dh.geometry.analyzer_config ({keyboard.name}, {fingers} fingers, "
             f"{bottom} bottom row, P_d={params.distance_scale})", "effort: 4"]
    lines += [" ".join(effort_text(grid[name].effort) for name in row) for row in rows]
    lines += [_PENALTIES.rstrip("\n"), "fingers: 4"]
    lines += [" ".join(str(by_id[grid[name].finger].analyzer_index) for name in row) for row in rows]
    lines += ["type:", "angle" if bottom == "angle" else "std"]
    return "\n".join(lines) + "\n"
