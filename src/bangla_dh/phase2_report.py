def _f(value: float, digits: int = 4) -> str:
    return f"{value:.{digits}f}"


def _pct(value: float, digits: int = 2) -> str:
    return f"{100 * value:.{digits}f} %"


def _show(unit: str) -> str:
    if unit == " ":
        return "␣ (space)"
    if unit in ("‌", "‍"):
        return "ZWNJ" if unit == "‌" else "ZWJ"
    if len(unit) == 1 and unicodedata.category(unit) in ("Mn", "Mc"):
        return "◌" + unit
    return unit


def _cp(unit: str) -> str:
    return " ".join(f"U+{ord(c):04X}" for c in unit)


def build_report(ev: dict) -> str:
    inv = load_inventory()
    corpus = json.loads((RESULTS / "corpus-manifest.json").read_text(encoding="utf-8"))
    validation = json.loads((RESULTS / "inventory-validation.json").read_text(encoding="utf-8"))
    names = list(corpus_files())
    records = {n: frequency_record(n) for n in names}
    train = records["bnwiki/train"]
    opt = json.loads(OPTIMIZATION_FREQUENCIES.read_text(encoding="utf-8"))
    uj = ev["unijoy"]["scores"]
    refs = ev["reference_layouts"]
    lb = ev["lower_bound_0"]
    cons = ev["scorer_consistency"]
    eng = ev["english_cross_check"]
    L: list[str] = []
    w = L.append

    w("# Phase 2 report: Bangla inventory, corpus, frequencies, scorer and baselines")
    w("")
    w("Generated by `bangla-dh evaluate-phase2`. Machine-readable record: [phase2.json](phase2.json); "
      "hashes of every input and output: [run-manifest.json](run-manifest.json).")
    w("")
    w("All Kala data was read in place and never modified. Every generated file is under "
      "`colemak-bangla/` (`data/` and `results/`); the code refuses to write anywhere else.")
    w("")
    w("Owner decisions D1–D6 are still open. This phase used the default of each and states where.")
    w("")
    w("## Summary")
    w("")
    u_space = train["space_units"] / train["N"]
    w(f"* **Inventory (D1 default):** {inv['counts']['placed']} placed symbols from Kala's alphabet, validated "
      f"against Unicode, plus ZWNJ/ZWJ tracked but not placed. ড় ঢ় য় are single units of two NFC code points.")
    tr = corpus["domains"]["bnwiki"]["splits"]
    w(f"* **Corpus (D4 default):** Bangla Wikipedia, {tr['train']['documents']:,} train and "
      f"{tr['heldout']['documents']:,} held-out articles ({(tr['train']['characters'] + tr['heldout']['characters']) / 1e6:,.0f} M characters "
      f"after cleaning and deduplication), split by document.")
    w(f"* **Frequencies:** N = {train['N']:,} typing units in the training split, space included "
      f"({_pct(u_space, 1)}); {train['out_of_inventory_characters']:,} characters outside the inventory "
      f"({_pct(train['out_of_inventory_characters'] / (train['N'] + train['out_of_inventory_characters']))}).")
    w(f"* **Scorer:** reproduces the analyzer port on all {len(eng['rows'])} English layouts within "
      f"{eng['max_abs_difference']:.1e}; unit tables, token table and an independent text verifier agree "
      f"within {cons['max_relative_difference']:.1e} (relative) on the held-out split.")
    w(f"* **NFC round trip:** {_round_trip_summary(ev)}")
    t = uj["bnwiki/train"]
    w(f"* **UniJoy baseline (Kala's file):** J0 = {_f(t['unrounded']['J0'])} on the model-optimal ANSI grid "
      f"({_f(t['traditional_unrounded']['J0'])} with traditional fingering). Same-finger pairs make up "
      f"{_f(t['unrounded']['E2_same_finger'])} of it. Kala's `bn_bijoy_layout.json` is identical to UniJoy, so there "
      f"is no separate Bijoy baseline.")
    base_first = refs["base-layer-first frequency greedy"]["optimization_frequencies"]["unrounded"]["J0"]
    w(f"* **Context:** a naive frequency-sorted layout scores {_f(base_first)} and a random layout "
      f"{_f(refs[next(k for k in refs if k.startswith('random'))]['optimization_frequencies']['unrounded']['J0'])}; "
      f"the elementary lower bound for the 90-slot problem is LB0 = {_f(lb['LB0'])}. These are reference "
      f"points, not candidates.")
    w("* **Decision needed (D2):** under J0 Shift and AltGr are free, so the E1 minimum stacks three symbols on "
      "each of the cheapest keys. Without a layer cost (M) a 90-slot optimum is not a usable keyboard; see section 8.")
    w("")

    # 1 inventory
    w("## 1. Symbol inventory (task 1)")
    w("")
    w(f"File: [`data/bangla-symbols-v1.json`](../../data/bangla-symbols-v1.json), symbol-list SHA-256 "
      f"`{inv['symbol_list_sha256'][:16]}…`, Unicode {inv['unicode_version']}.")
    w("")
    w("| Class | Count | Symbols |")
    w("| --- | --- | --- |")
    classes = {}
    for e in inv["symbols"]:
        classes.setdefault((e["class"], e["placed"]), []).append(e["symbol"])
    for (cls, placed), symbols in classes.items():
        shown = " ".join(_show(s) for s in symbols)
        w(f"| {cls}{'' if placed else ' (tracked, not placed)'} | {len(symbols)} | {shown} |")
    w("")
    w("Validation of Kala's data:")
    w("")
    for r in validation["rejected_kala_entries"]:
        w(f"* `{' '.join(r['kala'])}` in `{r['file']}` ({r['section']}): {r['reason']}.")
    for section, diff in validation["alphabet_copy_differences"].items():
        parts = [f"{k.replace('only_in_', 'only in `')}`: " + ", ".join(" ".join(x) for x in v) for k, v in diff.items() if v]
        w(f"* The two alphabet copies differ in `{section}`: " + "; ".join(parts) + ".")
    for name, c in validation["conjuncts"].items():
        if isinstance(c, dict):
            dup = len(c["duplicates_after_nfc"])
            examples = ", ".join(f"`{p['entry']}` ({p['problem']})" for p in c["problems"][:6])
            w(f"* `{name}`: {c['entries']} entries, {c['valid_clusters']} valid consonant clusters, "
              f"{len(c['problems'])} problems, {dup} duplicated entries. Examples: {examples}.")
    w("")
    w("Conjuncts are not symbols in v1: a conjunct is typed consonant, hasant, consonant. Kala's list is used "
      "only as a reference (section 4).")
    w("")

    # 2 grammar
    w("## 2. Typing grammar and the NFC round trip (task 2)")
    w("")
    w("Text is normalized (`bangla-dh-text-v1`: NFC, curly quotes → ASCII, hyphen variants → `-`, "
      "U+09F7 → `।`, invisible format characters except ZWJ/ZWNJ removed, whitespace collapsed) and split into "
      "units: one code point each, except ড ঢ য + nukta. Independent vowels and vowel signs are different units, "
      "hasant is its own unit. A key map turns text into keystrokes with the fewest keystrokes (ties: least key "
      "effort), and typing is simulated to decode. Characters a map cannot type are escaped (typed outside the "
      "model; they break bigrams). This includes invalid sequences such as hasant directly followed by a vowel sign "
      "(a legacy-conversion artifact in a few Wikipedia words): UniJoy's ্ + vowel-sign rule would turn them into an "
      "independent vowel, so the encoder never types them with that action.")
    w("")
    w("`NFC(decode(encode(T))) = NFC(T)`:")
    w("")
    w("| Key map | Text set | Texts | Round trip OK | Failures | With untypable characters |")
    w("| --- | --- | --- | --- | --- | --- |")
    for keymap, sources in ev["round_trip"].items():
        for source, r in sources.items():
            w(f"| {keymap} | {source} | {r['texts']:,} | {r['round_trip_ok']:,} | {r['failures']} | "
              f"{r['texts_with_unproducible_characters']:,} |")
    w("")
    w(f"UniJoy cannot type these placed symbols: {', '.join(ev['unijoy']['placed_units_not_producible']) or 'none'}. "
      "Untypable characters in the corpus are mostly Latin letters and ASCII digits.")
    w("")

    # 3 corpus
    w("## 3. Corpus (task 3)")
    w("")
    w(f"Config: [`data/corpus-v1.json`](../../data/corpus-v1.json). Split: {corpus['split']['heldout_percent']} % of "
      f"documents held out by `sha256(salt:id)`. Deduplication: {corpus['deduplication']}. "
      f"Cleaning: `{corpus['cleaning']['version']}` (paragraphs need ≥ {corpus['cleaning']['min_tokens']} tokens and "
      f"≥ {int(100 * corpus['cleaning']['min_bengali_letter_share'])} % Bengali letters). Corpus files live in "
      "`data/corpus/` (not in Git) and are pinned by SHA-256 in the manifest.")
    w("")
    for name, d in corpus["domains"].items():
        src = d["source"]
        w(f"**{name}**: {d['label']}. Source `{src['path']}` ({src['bytes']:,} bytes in {src['parts']} ZIP chunk(s), "
          f"commit `{src['commit'][:12]}` of {src['repository']}, chunk-list SHA-256 `{src['sha256'][:16]}…`).")
        w("")
        counts = ", ".join(f"{k.replace('_', ' ')} {v:,}" for k, v in d["source_counts"].items())
        w(f"* Source counts: {counts}.")
        if d["paragraph_filter"]:
            pf = ", ".join(f"{k.replace('_', ' ')} {v:,}" for k, v in sorted(d["paragraph_filter"].items(), key=lambda kv: -kv[1]))
            w(f"* Line filter: {pf}.")
        w(f"* Duplicate paragraphs removed: {d['duplicate_paragraphs_removed']:,}; documents left empty: "
          f"{d['documents_without_new_paragraphs']:,}.")
        for split, s in d["splits"].items():
            w(f"* `{split}`: {s['documents']:,} documents, {s['paragraphs']:,} paragraphs, {s['characters']:,} characters.")
        w("")
    w("All of this text is encyclopedic; the news cross-check ([../phase3-crosscheck/REPORT.md](../phase3-crosscheck/REPORT.md)) "
      "and the mixed search ([../mix-search/REPORT.md](../mix-search/REPORT.md)) add newspaper and BARD text (D4).")
    w("")

    # 4 frequencies
    w("## 4. Frequencies (task 4)")
    w("")
    w("Counts are taken over running text inside paragraphs; no pair crosses a paragraph or document boundary. "
      "Space is an explicit unit. `u_i = n_i / N`, `v_ij = n_ij / N` (binary64). The optimization frequencies "
      f"([`frequencies/optimization-frequencies.json`](frequencies/optimization-frequencies.json)) use weights "
      f"{json.dumps(opt['weights'])} (D4 default).")
    w("")
    w("| Corpus | Documents | Tokens | Token types | N (units) | Space share | Out-of-inventory characters |")
    w("| --- | --- | --- | --- | --- | --- | --- |")
    for n, r in records.items():
        w(f"| {n} | {r['documents']:,} | {r['tokens']:,} | {r['token_types']:,} | {r['N']:,} | "
          f"{_pct(r['space_units'] / r['N'], 1)} | {r['out_of_inventory_characters']:,} |")
    w("")
    w("Most frequent units (training split):")
    w("")
    w("| Rank | Unit | Code points | u |")
    w("| --- | --- | --- | --- |")
    for i, (unit, count) in enumerate(list(train["unit_counts"].items())[:30], 1):
        w(f"| {i} | {_show(unit)} | {_cp(unit)} | {_pct(count / train['N'], 3)} |")
    w("")
    w("Most frequent adjacent pairs (excluding space):")
    w("")
    pairs = [(a, b, c) for a, b, c in train["bigram_counts"] if a != " " and b != " "][:20]
    w(" · ".join(f"{_show(a)}{_show(b)} {_pct(c / train['N'])}" for a, b, c in pairs))
    w("")
    oov_total = train["out_of_inventory_characters"]
    w(f"Characters outside the inventory (training split, {oov_total:,} in total). Input for D1:")
    w("")
    w("| Character | Code point | Count | Share of out-of-inventory |")
    w("| --- | --- | --- | --- |")
    for ch, count in list(train["out_of_inventory_counts"].items())[:20]:
        w(f"| {ch if ch.isprintable() else '·'} | {_cp(ch)} {unicodedata.name(ch, '')} | {count:,} | {_pct(count / oov_total, 1)} |")
    w("")
    cl = ev["clusters"]
    w(f"Consonant clusters in running text ({cl['corpus']}): {cl['cluster_tokens']:,} occurrences of "
      f"{cl['distinct_clusters']:,} distinct clusters; {_pct(cl['share_of_cluster_occurrences_in_kala_list'], 1)} of the "
      f"occurrences are in Kala's conjunct list, and {cl['kala_valid_clusters_never_seen']} valid Kala clusters never occur. "
      "Most frequent: " + ", ".join(f"{k} {c:,}" for k, c in cl["top"][:15]) + ". Frequent clusters missing from Kala's list: "
      + (", ".join(f"{k} {c:,}" for k, c in cl["frequent_missing_from_kala"][:10]) or "none") + ".")
    w("")

    # 5 scorer
    w("## 5. Bangla scorer (task 5)")
    w("")
    w("J0 = Σ u_i K(L(c_i)) + Σ_{i≠j} v_ij B(L(c_i), L(c_j)) on the model-optimal ANSI grid "
      "(P_d = 1.12, unrounded; every result is repeated on the one-decimal grid). B is the frozen Colemak-DH table "
      "including the middle–index benefit (D6 default). Space is a thumb unit with no cost (D2 default); Shift and "
      "AltGr cost nothing (M and Q off). For layouts that need several keystrokes per unit, J0 sums all keystrokes "
      "and all consecutive keystroke pairs and still divides by the same N, so every layout is scored per unit of "
      "the same text.")
    w("")
    w(f"* **English cross-check:** {len(eng['rows'])} layouts of the published comparison, `en_books.freq`, each with its "
      f"own config: largest difference to the analyzer port {eng['max_abs_difference']:.1e} "
      f"(the port stores frequencies in binary32). {'PASS' if eng['pass'] else 'FAIL'}.")
    w(f"* **Three routes, {cons['corpus']}, {cons['layout']}:** unit tables {cons['J0_unit_tables']:.12f}, "
      f"token table {cons['J0_token_table']:.12f}, independent verifier {cons['J0_independent_verifier']:.12f} "
      f"(N {cons['verifier_N']:,} = {cons['table_N']:,}). {'PASS' if cons['pass'] else 'FAIL'}.")
    w("")

    # 6 baselines
    w("## 6. Baselines (task 6)")
    w("")
    w(f"UniJoy from `{ev['unijoy']['source']}` (SHA-256 `{ev['unijoy']['sha256'][:16]}…`): Kala's virtual-key layers "
      "plus its sequences (hasant + vowel sign → independent vowel). Avro is phonetic and has no key map. "
      f"`bn_bijoy_layout.json` is {'identical to' if ev['unijoy']['bijoy_file_identical_to_unijoy'] else 'different from'} "
      "UniJoy's layers, so Kala holds no distinct Bijoy layout; a real Bijoy baseline needs a source the owner approves.")
    w("")
    w("| Corpus | Grid | J0 | E1 | E2 | same finger | neighbour penalty | middle–index benefit | keystrokes per non-space unit | escaped characters |")
    w("| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |")
    for n, grids in uj.items():
        for g, r in grids.items():
            w(f"| {n} | {g.replace('_', ' ')} | {_f(r['J0'])} | {_f(r['E1'])} | {_f(r['E2'])} | {_f(r['E2_same_finger'])} | "
              f"{_f(r['E2_neighbour_penalty'])} | {_f(r['E2_neighbour_benefit'])} | {_f(r['keystrokes_per_non_space_unit'])} | "
              f"{r['escaped_characters']:,} |")
    w("")
    w("Largest penalty contributions for UniJoy (training split, model-optimal grid, contribution to J0):")
    w("")
    w("| Kind | Keys | Output | Contribution |")
    w("| --- | --- | --- | --- |")
    for p in uj["bnwiki/train"]["unrounded"]["top_penalty_pairs"][:12]:
        w(f"| {p['kind'].replace('_', ' ')} | {p['keys']} | {p['outputs']} | {_f(p['contribution'])} |")
    w("")

    # 7 reference points
    w("## 7. Reference points for Phase 3 (not candidates)")
    w("")
    w("Scored with the optimization frequencies on the 90 v1 slots (30 main-block keys × base/Shift/AltGr).")
    w("")
    w("| Layout | J0 | E1 | E2 | same-finger pair frequency |")
    w("| --- | --- | --- | --- | --- |")
    w(f"| UniJoy (bnwiki/train, for comparison) | {_f(t['unrounded']['J0'])} | {_f(t['unrounded']['E1'])} | {_f(t['unrounded']['E2'])} | |")
    for label, e in refs.items():
        r = e["optimization_frequencies"]["unrounded"]
        w(f"| {label} | {_f(r['J0'])} | {_f(r['E1'])} | {_f(r['E2'])} | {_pct(r['same_finger_bigram_frequency'])} |")
    w("")
    w(f"Elementary lower bound (RESEARCH_SPEC 8.3), scope: {lb['scope']}: E1_min = {_f(lb['E1_min'])}, "
      f"min B = {lb['min_B']}, placed pair mass Σv = {_f(lb['placed_pair_mass'])}, **LB0 = {_f(lb['LB0'])}**. "
      "It is valid but weak; Phase 4 needs QAP relaxations for useful gaps.")
    w("")

    # 8 decisions
    w("## 8. Findings that need owner decisions")
    w("")
    w("* **D2, layer cost.** J0 inherits the original's free Shift. With three free layers the E1 minimum puts three "
      "symbols on each of the cheapest keys (the unigram-greedy row above). Only the same-key penalty (2.5) pushes "
      "back. A Bangla layout needs M (and probably Q) before a 90-slot search is meaningful; the spec requires them "
      "to be measured, not assigned. Options: measure Shift/AltGr timing, restrict v1 to a base layer of 30 "
      "symbols plus fixed Shift pairs, or search the base layer under J0 and assign Shift by a separate rule.")
    w("* **D1, inventory.** The out-of-inventory table shows what Kala's alphabet lacks, chiefly `.` "
      "and Latin text. ZWNJ/ZWJ are tracked but not placed; standard spellings such as র‍্যাব need ZWJ. Digits are "
      "placed among the 90 main-block slots in this default; keeping them on the number row would change the scope.")
    w("* **D3, fingering.** UniJoy is learned with traditional fingering; it scores "
      f"{_f(t['traditional_unrounded']['J0'])} on the traditional grid against {_f(t['unrounded']['J0'])} on the model-optimal grid.")
    w("* **D4, corpus.** Phase 2 uses encyclopedic text only; the news cross-check and the mixed search later add news, "
      "so domain weights matter.")
    w("")
    w("## 9. Reproduce")
    w("")
    w("```bash")
    w("bangla-dh build-inventory")
    w("bangla-dh fetch-data --package wikipedia && bangla-dh prepare-data --package wikipedia")
    w("bangla-dh build-corpus        # checks the prepared Wikipedia against data/datasets.lock.json")
    w("bangla-dh compute-frequency")
    w("bangla-dh evaluate-phase2")
    w("```")
    w("")
    return "\n".join(L)


def _round_trip_summary(ev: dict) -> str:
    total = fails = 0
    for sources in ev["round_trip"].values():
        for r in sources.values():
            total += r["texts"]
            fails += r["failures"]
    return f"{total:,} texts (Kala's evaluation word lists and held-out token types) through two key maps, {fails} failure{'' if fails == 1 else 's'}."


def run_and_write() -> int:
    evaluation = run_evaluation()
    outputs = [write_json(RESULTS / "phase2.json", evaluation, indent=1),
               write_text(RESULTS / "REPORT.md", build_report(evaluation))]
    produced = sorted(FREQUENCIES.glob("*.json")) + [RESULTS / "inventory-validation.json", RESULTS / "corpus-manifest.json"]
    outputs.append(write_json(RESULTS / "run-manifest.json", manifest(produced + outputs, evaluation)))
    for path in outputs:
        print(path)
    checks = {"english_cross_check": evaluation["english_cross_check"]["pass"],
              "scorer_consistency": evaluation["scorer_consistency"]["pass"],
              "round_trip": all(r["failures"] == 0 for s in evaluation["round_trip"].values() for r in s.values())}
    for name, ok in checks.items():
        print(f"{'PASS' if ok else 'FAIL'}  {name}")
    return 0 if all(checks.values()) else 1
