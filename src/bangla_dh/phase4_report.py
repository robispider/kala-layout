"""Phase 4 report: ``bangla-dh evaluate-phase4`` writes results/phase4/
``phase4.json`` (full record), ``REPORT.md`` and ``run-manifest.json``."""
from __future__ import annotations

import json

from .bangla.styles import STYLES
from .paths import write_json, write_text
from .phase2_report import _f, _pct
from .phase4 import CERTIFICATES, RESULTS, acceptance, lp_duals_file, manifest, run_evaluation

PARAMETER_LABEL = {"P_x": "P_x (lateral multiplier)", "P_d": "P_d (distance scale)", "P_f_pinky": "P_f pinky",
                   "P_f_ring": "P_f ring", "P_f_middle": "P_f middle", "lambda_m": "λ_m (Shift cost scale)"}


def _g(value, digits: int = 6) -> str:
    return "–" if value is None else f"{value:.{digits}f}"


def _gap(value) -> str:
    return "–" if value is None else f"{value:.2f} %"


def build_report(ev: dict) -> str:
    certs, checks, sens, sums, lps = ev["certificates"], ev["checks"], ev["sensitivity"], ev["summaries"], ev["cell_lp"]
    ok = acceptance(ev)
    L: list[str] = []
    w = L.append

    w("# Phase 4 report: integer model, certified bounds and sensitivity")
    w("")
    w("Generated by `bangla-dh evaluate-phase4` from `bangla-dh certify` and `bangla-dh sensitivity`. "
      "Machine-readable record: [phase4.json](phase4.json); one certificate per style in "
      "[certificates/](certificates/); hashes of every input and output: [run-manifest.json](run-manifest.json).")
    w("")
    w("**Scope of every certificate** (RESEARCH_SPEC section 8.5 asks for exact scope labels): " + ev["scope"] +
      ". Nothing below is a claim about the full 90-slot keyboard, another grid or fingering, or a corpus other "
      "than bnwiki/train; held-out and news text appear only in the sensitivity part.")
    w("")
    w("Decisions used: D5 default (integer scale 10^6), D3 default (model-optimal fingering), D6 default "
      "(middle–index benefit kept). Owner rule of 10 October 2026 for repeated presses in B and D (section 7). "
      "Solver: " + certs[STYLES[0]].get("cpsat_full", {}).get("solver", "OR-Tools").replace(" CP-SAT", "") +
      " (approved by the owner, 10 October 2026).")
    w("")

    w("## 1. Summary")
    w("")
    w("| Style | Best found J1 (UB) | Best lower bound (LB) | Bound from | Gap | Classification | "
      "Proven in a neighbourhood |")
    w("| --- | --- | --- | --- | --- | --- | --- |")
    for s in STYLES:
        sm = sums[s]
        proofs = certs[s]["proofs"]
        scoped = []
        if proofs.get("exchange", {}).get("proven"):
            scoped.append(f"any move of ≤ {proofs['exchange']['k_max']} labels")
        top = proofs.get("top_k", {}).get("largest_proven")
        if top:
            scoped.append(f"top-{top} labels free")
        for layer in ("base", "shift"):
            if proofs.get(f"{layer}_layer", {}).get("proven_optimal_hint"):
                scoped.append(f"{layer} layer free")
        w(f"| {s} | {_g(sm['UB_J'])} | {_g(sm['LB_J'])} | {sm['LB_source']} | {_gap(sm['gap_percent'])} | "
          f"{sm['classification']} | {'; '.join(scoped) or '–'} |")
    w("")
    proven_worse = [(s, t) for s in STYLES for t in STYLES if s != t and sums[s]["LB_J"] > sums[t]["UB_J"]]
    w("**Between styles.** A style whose lower bound exceeds another style's best found J1 cannot beat it with "
      "any layout of the scope: " + ("; ".join(f"every {s} layout is worse than the {t} layout found"
                                                 for s, t in proven_worse) or "no such pair") +
      ". The remaining order (" + " < ".join(sorted((s for s in STYLES if not any(s == a for a, _ in proven_worse)),
                                                   key=lambda s: sums[s]["UB_J"])) +
      ") is best found only: the gaps are larger than the differences between those styles.")
    w("")
    w("Reading the table: the Phase 3 layouts are unchanged (section 7). For each style the true optimum J1* of "
      "the stated scope lies in [LB, UB]. The gap is the most any layout in that scope could improve on the "
      "Phase 3 layout. 'Proven in a neighbourhood' lists exact results: no layout reachable by the stated "
      "change is better, which is a proof for that neighbourhood only, not for the whole problem.")
    w("")

    w("## 2. Integer model (task 1)")
    w("")
    w("Frozen rule (`search/integer.py`): raw keystroke and pair counts of the training tables, "
      "K̂ = 10^6 K, M̂ = 10^6 M, B̂ = 10^6 B. The grid stores K with six decimals and B is a multiple of 0.1, so "
      "every coefficient is an exact integer (the code refuses any value that is not) and "
      "J = Z / (N · 10^6) holds exactly. A bound on the integer objective Z is therefore a bound on J with no "
      "rounding error. The only rounding left is the grid's: its efforts are the Fitts formula rounded to six "
      "decimals, which moves any layout's J1 by at most the bound below.")
    w("")
    w("| Style | N (train) | UB as integer Z | Float search J1 − exact J1 | Grid rounding bound on J1 | Largest coefficient |")
    w("| --- | --- | --- | --- | --- | --- |")
    for s in STYLES:
        im = certs[s]["integer_model"]
        w(f"| {s} | {certs[s]['N']:,} | {im['UB_Z']:,} | {im['float_vs_exact_difference']:.1e} | "
          f"{im['formula_rounding_bound_J']:.1e} | {im['max_abs_coefficient']:.2e} |")
    w("")

    w("## 3. Lower bounds (task 2)")
    w("")
    w("| Style | LB0 (spec 8.3) | Gilmore–Lawler | Cell LP (certified) | CP-SAT, full problem | UB |")
    w("| --- | --- | --- | --- | --- | --- |")
    for s in STYLES:
        b = sums[s]["bounds"]
        cell = lambda name: (f"{_g(b[name]['J'])} ({_gap(b[name]['gap_percent'])})" if name in b else "not run")  # noqa: E731
        w(f"| {s} | {cell('LB0')} | {cell('Gilmore-Lawler')} | {cell('cell LP')} | {cell('CP-SAT')} | "
          f"{_g(sums[s]['UB_J'])} |")
    w("")
    w("* **LB0** (RESEARCH_SPEC 8.3): the linear part at its rearrangement minimum and every searched pair at "
      "the smallest penalty (−0.2).")
    w("* **Gilmore–Lawler** (`search/bounds.py`): a linear assignment over each label's cost on each slot plus "
      "half the cheapest possible arrangement of its pair partners around that slot. The assignment is solved "
      "exactly in integers and re-solved by OR-Tools' linear sum assignment; both agree.")
    w("* **Cell LP** (`search/lp_bound.py`): the first-level RLT relaxation aggregated to the 19 finger-row cells "
      "of the 52 slots (B depends only on cells): joint cell distributions for every label pair, consistent "
      "with both labels' cells, and with i in cell c the other labels exactly fill every cell d. Solved by PDLP; "
      "the bound is **not** the solver's objective but a weak-duality bound recomputed in exact integer "
      "arithmetic from the duals (stored in `certificates/<style>-lp-duals.json.gz` and re-checked by "
      "`evaluate-phase4`), so it holds whatever the solver's tolerances. GLOP (simplex) did not solve this "
      "481,390-column LP in 30 minutes; PDLP (first-order) did, and its slightly inexact duals cost only the "
      "difference between 'solver objective' and 'certified' below.")
    w("* **CP-SAT, full problem**: the solver's best bound after the time limit, from the Phase 3 layout as a "
      "hint. It is a solver claim: re-running CP-SAT would be replication, not independent proof (RESEARCH_SPEC "
      "8.5). Its model is checked against exhaustive enumeration in section 4.")
    w("")
    for s in STYLES:
        lp = lps[s]
        if lp:
            w(f"Cell LP {s}: {lp['rows']:,} rows, {lp['columns']:,} columns, {lp['solver']}, status {lp['status']}, "
              f"solver objective {_g(lp['solver_objective_J'])}, certified {_g(lp['certified_J'])}, {lp['seconds']} s.")
    if any(lps.values()):
        w("")
    for s in STYLES:
        full = certs[s].get("cpsat_full")
        if full:
            w(f"CP-SAT full {s}: {full['status']} after {full['seconds']} s ({full['workers']} workers, "
              f"{full['pair_literals']:,} pair literals); best solution {_g(full['solution_J'])}"
              + (" (better than Phase 3)" if "improved_layout" in full else " (the Phase 3 layout)") + ".")
    w("")

    w("## 4. Scoped proofs (task 3)")
    w("")
    w("Each row is a proof for exactly the stated neighbourhood of the Phase 3 layout, with the other labels "
      "where they are. CP-SAT runs use the exact integer coefficients (no rounding) with gap limits 0, so "
      "OPTIMAL with a bound equal to the layout's Z is a proof.")
    w("")
    w("| Style | Neighbourhood | Layouts / method | Result | Seconds |")
    w("| --- | --- | --- | --- | --- |")
    for s in STYLES:
        p = certs[s]["proofs"]
        ex = p.get("exchange")
        if ex:
            total = sum(r["checked"] for r in ex["by_k"].values())
            closest = min(r["best_delta"] for r in ex["by_k"].values())
            n = certs[s]["N"] * certs[s]["scale"]
            w(f"| {s} | any 2–{ex['k_max']} labels moved | {total:,} layouts, exhaustive (standard library) | "
              f"{'proven: none better' if ex['proven'] else 'NOT proven'}; closest rival +{closest / n:.2e} J1 | "
              f"{ex['seconds']} |")
        e = p["exhaustive_check"]
        w(f"| {s} | top-{e['size']} labels free (model check) | {e['arrangements']:,} arrangements, exhaustive vs "
          f"CP-SAT | {'agree' if e['agree'] else 'DISAGREE'}; Phase 3 layout optimal: {e['hint_optimal']} | "
          f"{e['seconds']:.1f} |")
        for r in p.get("top_k", {}).get("runs", []):
            w(f"| {s} | top-{r['size']} labels free | CP-SAT | {r['status']}, "
              f"{'proven optimal' if r['proven_optimal_hint'] else 'bound ' + _g(r['bound_J'])} | {r['seconds']} |")
        for layer in ("base", "shift"):
            r = p.get(f"{layer}_layer")
            if r:
                w(f"| {s} | all 26 {layer}-layer labels free | CP-SAT | {r['status']}, "
                  f"{'proven optimal' if r['proven_optimal_hint'] else 'bound ' + _g(r['bound_J'])} | {r['seconds']} |")
    w("")
    w("'Top-k labels free': the k labels with the most keystrokes may take any arrangement on their own slots; "
      "the other 52 − k stay where Phase 3 put them. 'Layer free': the 26 labels of one layer may be "
      "rearranged on that layer. The exhaustive check enumerates every arrangement of the top-9 labels "
      "independently of the CP-SAT model and must reach the same minimum.")
    w("")

    w("## 5. Sensitivity (task 4)")
    w("")
    st = sens["settings"]
    w(f"{sens['samples']['count']:,} parameter vectors θ drawn uniformly (seed {st['seed']}) from the ranges "
      "below; each rebuilds the ANSI effort grid with the Phase 1 Fitts model (fingers re-chosen per θ under "
      "model-optimal fingering) and scales the Shift cost. Corpus: " + sens["corpus"] + ". Bangla-DH layouts use "
      "model-optimal fingering; each baseline keeps the better of model-optimal and traditional fingering. These "
      "parameters are new to Phase 4 and are reported separately from J0/J1.")
    w("")
    w("| Parameter | Nominal | Range |")
    w("| --- | --- | --- |")
    for name, (low, high) in st["ranges"].items():
        w(f"| {PARAMETER_LABEL[name]} | {st['nominal'][name]:g} | {low:.3f} – {high:.3f} |")
    w("")
    bases = sens["baselines"]
    w("R(L, baseline) = share of θ with J1_θ(L) ≤ J1_θ(baseline) (a model-sensitivity statistic, not a "
      "probability of comfort):")
    w("")
    w("| Layout | J1 median (5–95 %) | " + " | ".join(f"R vs {b}" for b in bases) + " |")
    w("| --- | --- |" + " --- |" * len(bases))
    for name, row in sens["samples"]["summary"].items():
        q = row["J1"]
        w(f"| {name} | {_f(q['median'])} ({_f(q['p05'])}–{_f(q['p95'])}) | " +
          " | ".join(_pct(row[f'R vs {b}'], 1) for b in bases) + " |")
    w("")
    w("Share of θ in which each style has the lowest J1 among A–D: " +
      ", ".join(f"{n.replace('Bangla-DH ', '')} {_pct(v, 1)}" for n, v in sens["samples"]["best_style_share"].items()) + ".")
    w("")
    w("One parameter at a time (others nominal), J1 on " + sens["corpus"] + ":")
    w("")
    layouts = [n for n in sens["layouts"] if n.startswith("Bangla-DH")]
    best_base = lambda j: min((j[b] for b in bases if j.get(b) is not None), default=None)  # noqa: E731
    w("| Parameter | Value | " + " | ".join(n.replace("Bangla-DH ", "") for n in layouts) + " | Best baseline |")
    w("| --- | --- |" + " --- |" * (len(layouts) + 1))
    for row in sens["one_at_a_time"]:
        p = row["parameter"]
        w(f"| {PARAMETER_LABEL[p]} | {row['theta'][p]:.3f} | " + " | ".join(_f(row["J1"][n]) for n in layouts) +
          f" | {_f(best_base(row['J1']))} |")
    w("")
    w("Regret: each Phase 3 layout re-optimized (descent + 1,000 iterations of iterated local search, training "
      "frequencies) under the extreme values of one parameter. The regret is how much lower J1 a layout "
      "optimized for that θ reaches; small regret means the Phase 3 layout stays near the best found for that θ.")
    w("")
    w("| θ | " + " | ".join(f"{s} regret (labels moved)" for s in STYLES) + " |")
    w("| --- |" + " --- |" * len(STYLES))
    by = {}
    for r in sens["regret"]:
        by.setdefault(r["theta_label"], {})[r["style"]] = r
    for label, row in by.items():
        name, end = label.rsplit(" ", 1)
        w(f"| {PARAMETER_LABEL.get(name, name)}, {end} | " + " | ".join(f"{row[s]['regret_percent']:.2f} % ({row[s]['labels_moved']})" for s in STYLES) + " |")
    w("")

    w("## 6. Checks")
    w("")
    for name, passed in ok.items():
        w(f"* {'PASS' if passed else 'FAIL'}: {name}")
    w("")
    if all("verifier" in c for c in checks.values()):
        w("| Style | Verifier J1 (train text) | Integer UB J1 | Equal as exact rationals | N, keystrokes, escapes |")
        w("| --- | --- | --- | --- | --- |")
        for s in STYLES:
            c = checks[s]
            w(f"| {s} | {_g(c['verifier']['J1'], 9)} | {_g(certs[s]['integer_model']['UB_J'], 9)} | "
              f"{'yes' if c['verifier_equals_integer_exactly'] else 'NO'} | {'match' if c['verifier_counts_match'] else 'DIFFER'} |")
        w("")
    w("The independent verifier (`scoring/verify.py`, shares no code with the styles, tables or search) types "
      "the training text itself, counts presses and penalties, and forms J1 once as an exact rational; it must "
      "equal Z / (N · 10^6) of the integer model exactly.")
    w("")

    w("## 7. Repeated presses in B and D (owner rule, 10 October 2026)")
    w("")
    w("Phase 3 left an owner point: B and D could not type a vowel sign followed by the same vowel's independent "
      "form (তিনিই). The owner's timing-free rule: consecutive presses of one vowel key whose first press gave a "
      "sign are split into pairs, with one single press first when their number is odd; a single is the sign, a "
      "pair the independent vowel (3 presses → ি ই, 4 → ই ই, 5 → ি ই ই). The next different key ends the run. "
      "It is implemented in the typing machine (`bangla/styles.py`) and, separately, in the independent verifier. "
      "Phase 3 and the cross-check were regenerated with it: no label of any best layout moved; B and D J1 rose "
      "by about 0.0003 because these words are now typed instead of escaped. C is unchanged (its three-press rule "
      "is not defined).")
    w("")

    w("## 8. What is and is not established")
    w("")
    w("* Every style's Phase 3 layout is a **bounded near-optimum** of its stated scope: no layout of that scope "
      "is better by more than the gap in section 1, and the bound is certified by exact arithmetic, independently "
      "of solver tolerances.")
    w("* Within the listed neighbourhoods the layouts are **proven optimal**. Outside them, a better layout may "
      "exist; nothing here rules it out beyond the gap.")
    w("* The certificates hold for the training frequencies and the model parameters of Phase 1. Section 5 "
      "shows how far the conclusions survive other parameters; it proves nothing.")
    w("* Not covered: the third (conjunct) layer, other keyboards, and typing tests with people (Phase 5).")
    w("")
    return "\n".join(L) + "\n"


def run_and_write(verify: bool = True, report_only: bool = False) -> int:
    if report_only:
        evaluation = json.loads((RESULTS / "phase4.json").read_text(encoding="utf-8"))
    else:
        evaluation = run_evaluation(verify=verify)
    outputs = [write_json(RESULTS / "phase4.json", evaluation, indent=1),
               write_text(RESULTS / "REPORT.md", build_report(evaluation))]
    produced = sorted(CERTIFICATES.glob("*.json")) + [lp_duals_file(s) for s in STYLES if lp_duals_file(s).exists()] + \
        [RESULTS / "sensitivity.json"]
    outputs.append(write_json(RESULTS / "run-manifest.json", manifest(produced + outputs)))
    for path in outputs:
        print(path)
    checks = acceptance(evaluation)
    for name, passed in checks.items():
        print(f"{'PASS' if passed else 'FAIL'}  {name}")
    return 0 if all(checks.values()) else 1
