"""Challenge leaderboard: score every layout file in ``submissions/``.

A challenger adds one JSON file (the format of ``challenge/A-reference.json``) to
``submissions/`` in a pull request. This module re-scores every file with the public
scorer ``challenge/bangla_dh_challenge.py`` (never trusting a reported score), ranks the
valid ones per style by exact J1, and writes ``submissions/leaderboard.json`` and
``submissions/LEADERBOARD.md``. The same command with ``--check`` is what the pull
request workflow runs: it fails when a submitted file is invalid.

Ranking rules: lower exact J1 is better; two files with the same layout count once
(the earlier file name keeps the place); ties in J1 are broken by file name, and the
maintainers use the Git history of a tie.
"""
from __future__ import annotations

import json
from fractions import Fraction
from pathlib import Path

from .challenge import SCRIPT, load_scorer
from .paths import PROJECT_ROOT, write_json, write_text

SUBMISSIONS = PROJECT_ROOT / "submissions"
MAX_BYTES = 64_000
NAMES = {"A": "Kala Goti (style A)", "D": "Kala Jhor (style D)"}


def _files(paths: list[str] | None) -> list[Path]:
    if paths:
        return [Path(p) for p in paths]
    return sorted(p for p in SUBMISSIONS.glob("*.json") if p.name != "leaderboard.json")


def score_files(paths: list[str] | None = None) -> dict:
    scorer = load_scorer(SCRIPT)
    data, data_sha256 = scorer.load_data()
    model = scorer.Model(data)
    rows, problems, seen = [], [], {}
    for style, spec in data["styles"].items():  # a copy of the reference layout is not a submission
        _, placed, _ = scorer.parse_layout({"style": style, "layout": spec["reference"]["layout"]}, data)
        seen[scorer.layout_hash(style, placed)] = f"the {NAMES[style]} reference"
    for path in _files(paths):
        label = path.name
        if path.stat().st_size > MAX_BYTES:
            problems.append({"file": label, "problems": [f"file larger than {MAX_BYTES} bytes"]})
            continue
        try:
            submission = scorer.read_layout_file(path)
        except (OSError, ValueError) as error:
            problems.append({"file": label, "problems": [str(error)]})
            continue
        result = scorer.evaluate(submission, data, data_sha256, model)
        if not result["valid"]:
            problems.append({"file": label, "problems": result["problems"]})
            continue
        if result["layout_sha256"] in seen:
            problems.append({"file": label, "problems": [f"same layout as {seen[result['layout_sha256']]}"]})
            continue
        seen[result["layout_sha256"]] = label
        author = submission.get("author") if isinstance(submission, dict) else None
        rows.append({"file": label, "name": result["name"] or label, "author": str(author or "")[:60],
                     "style": result["style"], "J1": result["J1"], "J1_exact": result["J1_exact"],
                     "vs_reference_percent": result["difference_vs_reference_percent"],
                     "beats_reference": result["beats_reference"], "held_out_average": result["held_out"]["average"],
                     "held_out": result["held_out"]["J1"], "public_rank": result["held_out"]["public_rank"],
                     "layout_sha256": result["layout_sha256"]})
    board = {"data_version": data["version"], "data_sha256": data_sha256, "script_version": scorer.SCRIPT_VERSION,
             "styles": {}, "problems": problems}
    for style, spec in data["styles"].items():
        ref = spec["reference"]
        entries = sorted((r for r in rows if r["style"] == style), key=lambda r: (Fraction(r["J1_exact"]), r["file"]))
        board["styles"][style] = {
            "reference": {"name": NAMES[style], "J1": round(float(Fraction(ref["J1_exact"])), 9)},
            "entries": entries}
    return board


def render(board: dict) -> str:
    L = ["# Challenge leaderboard", "",
         f"Generated by `python -m bangla_dh leaderboard` from the files in `submissions/`. Scorer "
         f"{board['script_version']}, data `{board['data_version']}` (SHA-256 `{board['data_sha256'][:16]}…`). "
         "Lower J1 is better; every file is re-scored with the public scorer.", ""]
    for style, part in board["styles"].items():
        ref = part["reference"]
        L += [f"## Style {style}: reference {ref['name']}, J1 {ref['J1']:.6f}", ""]
        if not part["entries"]:
            L += ["No submissions yet. Be the first: see [docs/CHALLENGE.md](../docs/CHALLENGE.md).", ""]
            continue
        L += ["| Rank | Layout | Author | J1 | vs reference | Held-out average | Beats reference |",
              "| --- | --- | --- | --- | --- | --- | --- |"]
        for rank, e in enumerate(part["entries"], 1):
            L.append(f"| {rank} | {e['name']} (`{e['file']}`) | {e['author'] or '-'} | {e['J1']:.6f} | "
                     f"{e['vs_reference_percent']:+.4f} % | {e['held_out_average']:.4f} | "
                     f"{'**yes**' if e['beats_reference'] else 'no'} |")
        L.append("")
    if board["problems"]:
        L += ["## Files that were not scored", ""]
        L += [f"* `{p['file']}`: {'; '.join(p['problems'])}" for p in board["problems"]]
        L.append("")
    return "\n".join(L)


def run(paths: list[str] | None = None, check: bool = False, diagnostics: str | Path | None = None) -> int:
    board = score_files(paths)
    if diagnostics is not None:
        try:
            from .experimental.submissions import report_optional
            accepted = {(e["file"], e["layout_sha256"]) for part in board["styles"].values() for e in part["entries"]}
            report_optional([str(p) for p in _files(paths)], diagnostics, accepted_pairs=accepted)
        except Exception as error:
            print(f"Optional diagnostics unavailable: {error}. Official results are unchanged.")
    if check:
        for entry in (e for part in board["styles"].values() for e in part["entries"]):
            print(f"ok  {entry['file']}: style {entry['style']}, J1 {entry['J1']:.6f} "
                  f"({entry['vs_reference_percent']:+.4f} % vs reference)"
                  + (", BEATS the reference" if entry["beats_reference"] else ""))
        for problem in board["problems"]:
            print(f"BAD {problem['file']}: {'; '.join(problem['problems'])}")
        return 1 if board["problems"] else 0
    write_json(SUBMISSIONS / "leaderboard.json", board, indent=1)
    write_text(SUBMISSIONS / "LEADERBOARD.md", render(board))
    print(render(board))
    return 0
