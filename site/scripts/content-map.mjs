export function sourcePath(page, locale) {
  return path.join(repoRoot, locale === 'en' ? '' : `translations/${locale}`, page.source);
}

const sourceRoutes = new Map(pages.map((page) => [page.source, page.route]));
// Links to other pages of the site become site routes; links to any other file or folder of
// the repository become GitHub links, so the Markdown works on GitHub and on the website.
export function rewriteLinks(markdown, source, locale) {
  return markdown.replace(/(!?\[[^\]]*\])\(([^)]+)\)/g, (match, label, href) => {
    if (/^(?:https?:|mailto:|#)/.test(href)) return match;
    const [target, anchor] = href.split('#');
    const resolved = path.posix.normalize(path.posix.join(path.posix.dirname(source), decodeURIComponent(target)));
    const route = sourceRoutes.get(resolved);
    if (route) return `${label}(${base}/${locale}/${route}/${anchor ? `#${anchor}` : ''})`;
    if (resolved.startsWith('..')) throw new Error(`Link leaves the repository in ${source}: ${href}`);
    const isFolder = !/\.[A-Za-z0-9]+$/.test(resolved);
    return `${label}(${repoUrl}/${isFolder ? 'tree' : 'blob'}/main/${resolved}${anchor ? `#${anchor}` : ''})`;
  });
}
